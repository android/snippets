package androidx.compose.ui.res

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.painter.Painter
import com.example.compose.snippets.SnippetDrawables
import com.example.compose.snippets.SnippetStrings
import org.jetbrains.compose.resources.painterResource as cmpPainterResource
import org.jetbrains.compose.resources.stringResource as cmpStringResource

/*
 * Android `androidx.compose.ui.res` APIs used by the shared snippets, backed by Compose
 * Multiplatform resources.
 *
 * `R` and the SnippetDrawables/SnippetStrings tables are generated by
 * `:preview:wasm:generateSnippetResources` from the `R.drawable.*` and `R.string.*` references in
 * the copied-in snippets. IDs start at 1 (0 means "no resource" on Android), so each `R` ID is
 * one more than its index in the table.
 */

@Composable
fun painterResource(id: Int): Painter = cmpPainterResource(SnippetDrawables[id - 1])

@Composable
fun stringResource(id: Int): String = cmpStringResource(SnippetStrings[id - 1])

@Composable
fun stringResource(id: Int, vararg formatArgs: Any): String =
    cmpStringResource(SnippetStrings[id - 1], *formatArgs)
